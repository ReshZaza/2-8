def add_examples(path, examples):
    text = path.read_text(encoding='utf-8')
    for heading, example in examples.items():
        marker = f'<h2>{heading}</h2>'
        idx = text.find(marker)
        if idx < 0:
            print('NOT FOUND', heading)
            continue
        # find end of article after this heading
        article_end = text.find('</article>', idx)
        if article_end < 0:
            print('NO ARTICLE END', heading)
            continue
        chunk = text[idx:article_end]
        if 'class="example-box"' in chunk:
            continue
        insert = f'<div class="example-box"><strong>ตัวอย่าง:</strong> {example}</div>'
        text = text[:article_end] + insert + text[article_end:]
    path.write_text(text, encoding='utf-8')

