from bs4 import BeautifulSoup
from pathlib import Path
base=Path('/mnt/data/edit_site')

def update(fname, cards):
    p=base/fname
    s=BeautifulSoup(p.read_text(encoding='utf-8'),'html.parser')
    sec=s.select_one('.benefit-grid-images' if fname=='benefits.html' else '.law-grid-images')
    arts=sec.find_all('article', recursive=False)
    for i,(title,paras) in enumerate(cards):
        art=arts[i]
        h=art.find('h2'); h.string=title
        # remove old paragraphs and add requested richer text
        for old in art.find_all('p'): old.decompose()
        for txt in paras:
            pp=s.new_tag('p'); pp.string=txt; art.append(pp)
    if fname=='laws.html':
        arts[5]['class']=['law-card-6']
        img=arts[5].find('img')
        img['alt']='การรายงานและติดตามผลด้านสิ่งแวดล้อม'
        img['onerror']="this.style.display='none'"
    # ensure every image failure cannot hide its card
    for img in sec.find_all('img'):
        img['onerror']=img.get('onerror','this.style.display=\'none\'')
    style=s.new_tag('style')
    if fname=='benefits.html':
        style.string='''
.benefit-grid-images article{min-height:100%;}
.benefit-grid-images article p{line-height:1.9;margin-top:8px;}
.benefit-grid-images article:last-child{margin-bottom:8px;}
'''
    else:
        style.string='''
.law-grid-images article{min-height:100%;}
.law-grid-images article p{line-height:1.9;margin-top:8px;}
.law-grid-images .law-card-6{display:block!important;visibility:visible!important;opacity:1!important;grid-column:auto;}
.law-grid-images .law-card-6 img{min-height:220px;}
'''
    s.body.append(style)
    p.write_text(str(s),encoding='utf-8')

